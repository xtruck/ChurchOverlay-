  let currentLanguage = "en"

  function t(key, params) {
    const dict = DICTIONARIES[currentLanguage] || DICTIONARIES.en
    let value = dict[key] ?? DICTIONARIES.en[key] ?? key
    if (params) {
      for (const paramKey of Object.keys(params)) {
        value = value.split("{" + paramKey + "}").join(String(params[paramKey]))
      }
    }
    return value
  }

  function applyTranslations() {
    document.title = t("app.title")
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"))
    })
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")))
    })
    document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")))
    })
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")))
    })
  }

  function setLanguage(lang) {
    currentLanguage = DICTIONARIES[lang] ? lang : "en"
    document.documentElement.lang = currentLanguage // screen readers pick the right voice
    applyTranslations()
    // Views that build text dynamically (the Overlay palette picker) rebuild on this.
    window.dispatchEvent(new Event("churchoverlay:languagechange"))
  }

  function getLanguage() {
    return currentLanguage
  }

  window.i18n = { t, applyTranslations, setLanguage, getLanguage }
